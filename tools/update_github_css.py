#!/usr/bin/python3
"""Regenerate data/styles/github*.css from sindresorhus/github-markdown-css on npm.

Usage:
    tools/update_github_css.py              # latest version
    tools/update_github_css.py 5.9.0        # a specific version
    tools/update_github_css.py --check      # exit 1 if a newer version exists, else 0

Each generated file = our header (name/description/scheme/upstream version)
+ the upstream CSS verbatim + a small layout section, because upstream leaves
page padding/centering to the host page. Do not edit the generated files by
hand; change this script and re-run it.

Only the Python standard library is used, so the GitHub Action needs no setup.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

PACKAGE = "github-markdown-css"
REGISTRY = "https://registry.npmjs.org"
STYLES_DIR = Path(__file__).resolve().parent.parent / "data" / "styles"
VERSION_RE = re.compile(rf"upstream: {PACKAGE} (\S+)")

# output file stem -> (upstream file, display name, description, scheme)
VARIANTS: dict[str, tuple[str, str, str, str]] = {
    "github": (
        "github-markdown.css",
        "GitHub",
        "GitHub's Markdown look; follows the system light/dark setting",
        "auto",
    ),
    "github-light": ("github-markdown-light.css", "GitHub Light", "GitHub's Markdown look, always light", "light"),
    "github-dark": ("github-markdown-dark.css", "GitHub Dark", "GitHub's Markdown look, always dark", "dark"),
}

LAYOUT_CSS = """
/* ---- xfce-md-viewer layout (not part of upstream) ---- */
html, body {
  margin: 0;
  padding: 0;
}
.markdown-body {
  box-sizing: border-box;
  min-height: 100vh;
  padding: 32px max(16px, calc((100% - 980px) / 2));
}
"""


def _fetch(url: str) -> bytes:
    if not url.startswith("https://"):
        raise ValueError(f"refusing non-https URL: {url}")
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310 — https enforced above
        return response.read()


def _metadata(version: str) -> dict:
    return json.loads(_fetch(f"{REGISTRY}/{PACKAGE}/{version}"))


def current_version() -> str | None:
    """Version recorded in the generated github.css header, or None if absent."""
    path = STYLES_DIR / "github.css"
    if not path.is_file():
        return None
    match = VERSION_RE.search(path.read_text(encoding="utf-8"))
    return match.group(1) if match else None


def _verified_tarball(meta: dict) -> bytes:
    data = _fetch(meta["dist"]["tarball"])
    algo, _, expected = meta["dist"]["integrity"].partition("-")
    if algo != "sha512":
        raise ValueError(f"unexpected integrity algorithm: {algo}")
    actual = base64.b64encode(hashlib.sha512(data).digest()).decode()
    if actual != expected:
        raise ValueError("tarball integrity check failed")
    return data


def _read_member(tar: tarfile.TarFile, name: str) -> str:
    member = tar.getmember(f"package/{name}")
    if not member.isfile():
        raise ValueError(f"{name} is not a regular file in the tarball")
    extracted = tar.extractfile(member)
    assert extracted is not None
    return extracted.read().decode("utf-8")


def _header(name: str, description: str, scheme: str, version: str, license_name: str) -> str:
    return (
        f"/* name: {name}\n"
        f"   description: {description}\n"
        f"   scheme: {scheme}\n"
        f"   upstream: {PACKAGE} {version} ({license_name}, Sindre Sorhus, https://github.com/sindresorhus/{PACKAGE})\n"
        f"   Generated by tools/update_github_css.py — do not edit by hand. */\n\n"
    )


def generate(version: str) -> str:
    """Write the github*.css styles for *version* ('latest' allowed). Returns the resolved version."""
    meta = _metadata(version)
    resolved = meta["version"]
    with tarfile.open(fileobj=io.BytesIO(_verified_tarball(meta)), mode="r:gz") as tar:
        for stem, (upstream_file, name, description, scheme) in VARIANTS.items():
            css = _read_member(tar, upstream_file)
            out = _header(name, description, scheme, resolved, meta.get("license", "MIT")) + css.rstrip() + "\n"
            (STYLES_DIR / f"{stem}.css").write_text(out + LAYOUT_CSS, encoding="utf-8")
    return resolved


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version", nargs="?", default="latest")
    parser.add_argument("--check", action="store_true", help="only report whether an update is available")
    args = parser.parse_args()

    have = current_version()
    if args.check:
        latest = _metadata("latest")["version"]
        print(f"current: {have}  latest: {latest}")
        return 0 if have == latest else 1

    resolved = generate(args.version)
    print(f"{PACKAGE}: {have} -> {resolved}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
